/** Returns plugin-specific FAQs first, then the common FAQs. */
export function getFaqs(pluginId: string): FaqItem[] {
  return [...(pluginSpecificFaqs[pluginId] ?? []), ...commonFaqs];
}

/** Builds the FAQPage JSON-LD object for a given plugin page. */
export function getFaqJsonLd(pluginId: string, pageUrl: string) {
  const faqs = getFaqs(pluginId);
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    '@id': `${pageUrl}#faq`,
    mainEntity: faqs.map((f) => ({
      '@type': 'Question',
      name: f.q,
      acceptedAnswer: {
        '@type': 'Answer',
        text: f.a,
      },
    })),
  };
}
