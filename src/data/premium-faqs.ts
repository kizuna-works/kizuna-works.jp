export function getPremiumFaqs(pluginId: string): FaqItem[] {
  return premiumFaqs[pluginId] ?? [];
}

/** Builds the FAQPage JSON-LD object for a premium plugin page. */
export function getPremiumFaqJsonLd(pluginId: string, pageUrl: string) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    '@id': `${pageUrl}#faq`,
    mainEntity: getPremiumFaqs(pluginId).map((f) => ({
      '@type': 'Question',
      name: f.q,
      acceptedAnswer: { '@type': 'Answer', text: f.a },
    })),
  };
}
